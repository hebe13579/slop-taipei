#!/usr/bin/env python3
# Issue #132 bake: SRTM GL1 (N25E121, fetched for the #117
# study) -> js/taipei-drape-data.js, a compact base64 int16 grid the
# drape module samples bilinearly. The drape DEM is lightly de-speckled
# (3x3 median, then 3x3 mean): SRTM is a surface model and single-posting
# radar spikes (a 97 m reading beside 9 m on the Yuanshan shoulder) would
# otherwise become cliffs in the draped roads. Raw values are kept out
# of the game; the study's dem_stats.py holds the raw sampler.
# Re-running this bake reproduces js/taipei-drape-data.js byte for byte
# (verified 2026-10-28); the baked file is committed, this script is
# its provenance.
import gzip, struct, math, base64, sys, os

HGT = sys.argv[1] if len(sys.argv) > 1 else '/home/hatch/workspace/slop-taipei/terrain-evidence/dem/N25E121.hgt.gz'
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', '..', 'js', 'taipei-drape-data.js')
raw = gzip.open(HGT, 'rb').read()
N = 3601
def raw_elev(lat, lon):
    fy = (26.0 - lat) * 3600.0; fx = (lon - 121.0) * 3600.0
    y0, x0 = int(math.floor(fy)), int(math.floor(fx))
    y0 = min(max(y0, 0), N - 2); x0 = min(max(x0, 0), N - 2)
    dy, dx = fy - y0, fx - x0
    def v(yy, xx):
        val = struct.unpack_from('>h', raw, (yy * N + xx) * 2)[0]
        return 0.0 if val < -1000 else float(val)
    return (v(y0,x0)*(1-dx)*(1-dy) + v(y0,x0+1)*dx*(1-dy) +
            v(y0+1,x0)*(1-dx)*dy + v(y0+1,x0+1)*dx*dy)

W, E, S, N_ = 121.458, 121.540, 25.058, 25.156
STEP = 1.0 / 3600.0
COLS = int(round((E - W) / STEP)) + 1   # 296
ROWS = int(round((N_ - S) / STEP)) + 1  # 354
# sample with 1-cell margin for the filters
g = [[raw_elev(N_ + STEP - r * STEP, W - STEP + c * STEP) for c in range(COLS + 2)] for r in range(ROWS + 2)]
def med3(g, r, c):
    vals = sorted(g[r+dr][c+dc] for dr in (-1,0,1) for dc in (-1,0,1))
    return vals[4]
g2 = [[med3(g, r, c) for c in range(1, COLS + 1)] for r in range(1, ROWS + 1)]
def mean3(g, r, c):
    return sum(g[r+dr][c+dc] for dr in (-1,0,1) for dc in (-1,0,1)) / 9.0
pad = [[0.0]*(COLS+2) for _ in range(ROWS+2)]
for r in range(ROWS):
    for c in range(COLS):
        pad[r+1][c+1] = g2[r][c]
grid = [[int(round(mean3(pad, r, c))) for c in range(1, COLS + 1)] for r in range(1, ROWS + 1)]
flat = [grid[r][c] for r in range(ROWS) for c in range(COLS)]
b64 = base64.b64encode(struct.pack('<%dh' % len(flat), *flat)).decode()
KX, KY = 100923.1, 110773.4
def xz(lat, lon): return ((lon - 121.565) * KX, -(lat - 25.033) * KY)
# Regions in game coords. Beitou = tile box 4 exactly. Yuanshan pocket
# refined from the DEM scan (drape-evidence/dem_probe.py): covers the
# hotel hill mass + approach roads, no more.
regions = [
    ('beitou', 25.150, 121.464, 25.113, 121.510),   # n, w, s, e
    ('yuanshan', 25.0830, 121.5198, 25.0725, 121.5335),
]
rects = []
for name, n, w, s, e in regions:
    x0, z0 = xz(n, w); x1, z1 = xz(s, e)
    rects.append({'name': name, 'minX': round(min(x0,x1),1), 'maxX': round(max(x0,x1),1),
                  'minZ': round(min(z0,z1),1), 'maxZ': round(max(z0,z1),1)})
js = f'''// GENERATED by tools/taipei/build-drape-dem.py (issue #132 prototype) — do not edit.
// SRTM GL1 grid (N25E121), de-speckled (3x3 median + 3x3 mean), int16 LE base64.
// Extent lon {W}..{E} x lat {S}..{N_} at 1 arc-second; row 0 = north edge.
export const DRAPE_GRID = {{ w: {W}, e: {E}, s: {S}, n: {N_}, cols: {COLS}, rows: {ROWS}, stepDeg: {STEP} }};
export const DRAPE_RECTS = {rects};
export const DRAPE_DATA_B64 = '{b64}';
'''
open(OUT, 'w').write(js)
def grid_at(lat, lon):
    fx = (lon - W) / STEP; fy = (N_ - lat) / STEP
    x0, y0 = int(math.floor(fx)), int(math.floor(fy))
    x0 = min(max(x0,0), COLS-2); y0 = min(max(y0,0), ROWS-2)
    dx, dy = fx-x0, fy-y0
    return (grid[y0][x0]*(1-dx)*(1-dy) + grid[y0][x0+1]*dx*(1-dy) + grid[y0+1][x0]*(1-dx)*dy + grid[y0+1][x0+1]*dx*dy)
print(f'baked {COLS}x{ROWS} -> {OUT} ({len(js)//1024} KB)')
print('hotel raw %.1f smoothed %.1f' % (raw_elev(25.0788, 121.5263), grid_at(25.0788, 121.5263)))
print('rects:', rects)
